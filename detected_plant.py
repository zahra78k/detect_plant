CLEAN_DATASET = 'plantvillage_clean'

if os.path.exists(CLEAN_DATASET):
    shutil.rmtree(CLEAN_DATASET)

os.makedirs(CLEAN_DATASET, exist_ok=True)

VALID_EXTENSIONS = ('.jpg', '.jpeg', '.png', '.bmp', '.webp')

clean_stats = []
global_hashes = set()

for class_name in class_names:
    src_dir = os.path.join(source_class_folders_dir, class_name)
    dst_dir = os.path.join(CLEAN_DATASET, class_name)
    os.makedirs(dst_dir, exist_ok=True)

    total = 0
    kept = 0
    bad = 0
    duplicate = 0

    image_paths = [
        p for p in glob.glob(os.path.join(src_dir, '*'))
        if p.lower().endswith(VALID_EXTENSIONS)
    ]

    for src_path in image_paths:
        total += 1

        # بررسی قابل خواندن بودن تصویر
        img = cv2.imread(src_path)
        if img is None or img.size == 0:
            bad += 1
            continue

        # حذف duplicate دقیق
        with open(src_path, 'rb') as f:
            file_hash = hashlib.md5(f.read()).hexdigest()

        if file_hash in global_hashes:
            duplicate += 1
            continue

        global_hashes.add(file_hash)

        dst_path = os.path.join(dst_dir, os.path.basename(src_path))
        shutil.copy2(src_path, dst_path)
        kept += 1

    clean_stats.append({
        'class': class_name,
        'total': total,
        'kept': kept,
        'bad_images': bad,
        'duplicates': duplicate
    })

clean_df = pd.DataFrame(clean_stats)

