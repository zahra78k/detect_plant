import gradio as gr

def dashboard_predict(image):
    if image is None:
        return '—', '—', '—', '—', None

    image_rgb = np.array(image).astype(np.uint8)
    image_bgr = cv2.cvtColor(
        image_rgb,
        cv2.COLOR_RGB2BGR
    )

    # Classification
    r = best_model(image_rgb, verbose=False)[0]

    pred_id = int(r.probs.top1)
    pred_name = r.names[pred_id]
    confidence = float(r.probs.top1conf)

    # Localization + severity
    severity, severity_level, leaf_mask, lesion_mask = estimate_severity(
        image_bgr
    )

    overlay = overlay_lesions(
        image_bgr,
        lesion_mask
    )

    overlay_rgb = cv2.cvtColor(
        overlay,
        cv2.COLOR_BGR2RGB
    )

    status = (
        'Healthy'
        if 'healthy' in pred_name.lower()
        else 'Diseased'
    )

    disease_text = f'{pred_name} ({status})'
    confidence_text = f'{confidence:.2%}'
    severity_text = f'{severity:.2f}%'

    return (
        disease_text,
        confidence_text,
        severity_text,
        severity_level,
        overlay_rgb
    )


