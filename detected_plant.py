"""## 8) Localization تقریبی"""

def estimate_leaf_mask(image_bgr):
    hsv = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2HSV)

    mask_green = cv2.inRange(
        hsv,
        np.array([20, 25, 25]),
        np.array([100, 255, 255])
    )

    kernel = np.ones((7, 7), np.uint8)

    mask = cv2.morphologyEx(
        mask_green,
        cv2.MORPH_CLOSE,
        kernel,
        iterations=2
    )

    mask = cv2.morphologyEx(
        mask,
        cv2.MORPH_OPEN,
        kernel,
        iterations=1
    )

    return mask


def estimate_lesion_mask(image_bgr, leaf_mask):
    hsv = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2HSV)
    h, s, v = cv2.split(hsv)

    brown = (
        (h >= 5) & (h <= 25) &
        (s >= 60) & (v <= 210)
    ).astype(np.uint8) * 255

    dark = (
        (v <= 75) & (s >= 25)
    ).astype(np.uint8) * 255

    yellow = (
        (h >= 20) & (h <= 38) &
        (s >= 70) & (v >= 80)
    ).astype(np.uint8) * 255

    lesion = cv2.bitwise_or(brown, dark)
    lesion = cv2.bitwise_or(lesion, yellow)
    lesion = cv2.bitwise_and(lesion, leaf_mask)

    kernel = np.ones((5, 5), np.uint8)

    lesion = cv2.morphologyEx(
        lesion,
        cv2.MORPH_OPEN,
        kernel
    )

    lesion = cv2.morphologyEx(
        lesion,
        cv2.MORPH_CLOSE,
        kernel
    )

    return lesion


def localize_lesions(image_bgr):
    leaf = estimate_leaf_mask(image_bgr)
    lesion = estimate_lesion_mask(image_bgr, leaf)
    return leaf, lesion


def overlay_lesions(image_bgr, lesion_mask):
    out = image_bgr.copy()

    contours, _ = cv2.findContours(
        lesion_mask,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_SIMPLE
    )

    for cnt in contours:
        if cv2.contourArea(cnt) >= 30:
            x, y, w, h = cv2.boundingRect(cnt)
            cv2.rectangle(
                out,
                (x, y),
                (x + w, y + h),
                (0, 0, 255),
                2
            )

    return out

"""## 9) Severity Estimation تقریبی"""

def estimate_severity(image_bgr):
    leaf_mask, lesion_mask = localize_lesions(image_bgr)

    leaf_pixels = np.count_nonzero(leaf_mask)
    lesion_pixels = np.count_nonzero(lesion_mask)

    if leaf_pixels == 0:
        return 0.0, 'Unknown', leaf_mask, lesion_mask

    severity = 100.0 * lesion_pixels / leaf_pixels
    severity = float(np.clip(severity, 0, 100))

    if severity < 10:
        level = 'Mild'
    elif severity < 30:
        level = 'Moderate'
    else:
        level = 'Severe'

    return severity, level, leaf_mask, lesion_mask

